LIBRARY ieee;
USE ieee.std_logic_1164.all;

ENTITY dec3to8 IS
    PORT(w  : IN  STD_LOGIC_VECTOR(3 DOWNTO 0);
         En : IN  STD_LOGIC;
         y  : OUT STD_LOGIC_VECTOR(0 TO 15));
END dec3to8;

ARCHITECTURE Behaviour OF dec3to8 IS
    SIGNAL Enw : STD_LOGIC_VECTOR(4 DOWNTO 0);
BEGIN
    Enw <= En & w; 

    WITH Enw SELECT
y <= "0000000000000001" WHEN "10000",  -- s0 = 5
     "0000000000000010" WHEN "10001",  -- s1 = 0
     "0000000000000100" WHEN "10010",  -- s2 = 1
     "0000000000001000" WHEN "10011",  -- s3 = 3
     "0000000000010000" WHEN "10100",  -- s4 = 1
     "0000000000100000" WHEN "10101",  -- s5 = 4
     "0000000001000000" WHEN "10110",  -- s6 = 6
     "0000000010000000" WHEN "10111",  -- s7 = 7
     "0000000100000000" WHEN "11000",  -- s8 = 9
     "0000001000000000" WHEN "11001",  
     "0000010000000000" WHEN "11010",  
     "0000100000000000" WHEN "11011",  
     "0001000000000000" WHEN "11100",  
     "0010000000000000" WHEN "11101",  
     "0100000000000000" WHEN "11110", 
     "1000000000000000" WHEN "11111",  
     "0000000000000000" WHEN OTHERS;

END Behaviour;
